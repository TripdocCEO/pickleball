def run() -> None:
    init_db()
    added = 0
    with get_conn() as conn:
        for p in POSTS:
            exists = conn.execute(
                "SELECT id FROM posts WHERE title = ?", (p["title"],)
            ).fetchone()
            if exists:
                continue
            cur = conn.execute(
                "INSERT INTO posts(category, title, body, author, pinned, views) VALUES (?,?,?,?,?,?)",
                (p["category"], p["title"], p["body"], p["author"], p["pinned"], p["views"]),
            )
            pid = cur.lastrowid
            for author, body in p["comments"]:
                conn.execute(
                    "INSERT INTO comments(post_id, author, body) VALUES (?,?,?)",
                    (pid, author, body),
                )
            added += 1
        total = conn.execute("SELECT COUNT(*) AS n FROM posts WHERE deleted = 0").fetchone()["n"]
    print(f"seed: {added}건 추가 / 전체 {total}건")


if __name__ == "__main__":
    run()
